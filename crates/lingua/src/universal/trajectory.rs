use crate::{
    serde_json::{Map, Value},
    universal::{AssistantContent, ToolContent, UserContent},
    Message, UniversalParams, UniversalUsage,
};
use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};
use serde_with::skip_serializing_none;
use std::vec::Vec;
use ts_rs::TS;

#[skip_serializing_none]
#[derive(Debug, Clone, Serialize, Deserialize, TS)]
#[ts(export)]
pub struct Trajectory {
    pub scope: Vec<Scope>,
    pub agent: Agent,
    #[ts(optional)]
    pub sections: Option<Vec<Section>>,
    #[ts(optional)]
    pub findings: Option<Vec<Finding>>,
    pub turns: Vec<Turn>,
    #[ts(type = "Record<string, unknown>")]
    pub metadata: Map<String, Value>,
    #[ts(optional)]
    pub version: Option<String>,
    /// Audio recordings logged anywhere in the trace, in span order.
    #[ts(optional)]
    pub recordings: Option<Vec<AudioRecording>>,
    /// Speech messages keyed by native identity, joining what a model generated, what was played
    /// or heard, and the model calls whose context included each one. Ordered by speech start.
    #[ts(optional)]
    pub voice_messages: Option<Vec<VoiceMessage>>,
    /// Which voice messages each model call in a voice trace received as context, in call order.
    #[ts(optional)]
    pub voice_contexts: Option<Vec<VoiceContext>>,
}

#[skip_serializing_none]
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, TS)]
pub struct AudioRecording {
    pub id: String,
    /// Span holding the audio attachment; absent while the recording is pending or omitted.
    #[ts(optional)]
    pub attachment_span_id: Option<String>,
    /// JSON pointer to the attachment in that span, like `/input/audio/call-0000`.
    #[ts(optional)]
    pub attachment_pointer: Option<String>,
    /// Segments of one recording share a group id.
    #[ts(optional)]
    pub group_id: Option<String>,
    #[ts(optional)]
    pub mime_type: Option<String>,
    #[ts(optional)]
    pub duration_ms: Option<f64>,
    #[ts(optional)]
    pub channel_count: Option<u32>,
    /// What each channel carries, like `session_input` or `local_audio_output`.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    #[ts(optional, as = "Option<Vec<AudioChannel>>")]
    pub channels: Vec<AudioChannel>,
    /// Unix milliseconds of offset 0, when the recording places itself on the call clock.
    #[ts(optional)]
    pub origin_unix_ms: Option<f64>,
    /// `pending`, `ready`, or `omitted`.
    #[ts(optional)]
    pub state: Option<String>,
    #[ts(optional)]
    pub truncated: Option<bool>,
    #[ts(optional)]
    pub reason: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, TS)]
pub struct AudioChannel {
    pub index: u32,
    pub boundary: String,
}

/// A stretch of one recording, in milliseconds from the start of that recording.
#[skip_serializing_none]
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, TS)]
#[ts(export)]
pub struct AudioSelection {
    pub recording_id: String,
    pub recording_span_id: String,
    #[ts(optional)]
    pub channel_index: Option<u32>,
    pub start_offset_ms: f64,
    pub end_offset_ms: f64,
}

/// One spoken message: a `user_speech` or `agent_speech` span and what it joins.
#[skip_serializing_none]
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, TS)]
#[ts(export)]
pub struct VoiceMessage {
    /// The native message id when the framework logs a unique one, else the speech span's row id.
    pub id: String,
    pub speaker: VoiceSpeaker,
    /// Row id of the speech span.
    pub speech_id: String,
    /// Native message ids logged on the speech span, like `contrib.livekit.message_ids`.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    #[ts(optional, as = "Option<Vec<String>>")]
    pub native_ids: Vec<String>,
    /// What was played (agent) or heard (user), from the speech span itself.
    #[ts(optional)]
    pub spoken_text: Option<String>,
    /// Text output of the model call this message was generated by.
    #[ts(optional)]
    pub generated_text: Option<String>,
    /// Row id of that model call.
    #[ts(optional)]
    pub generated_step_id: Option<String>,
    /// Whether spoken and generated text differ exactly; absent unless both are known.
    /// A difference is not evidence of an interruption.
    #[ts(optional)]
    pub text_differs: Option<bool>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    #[ts(optional, as = "Option<Vec<AudioSelection>>")]
    pub selections: Vec<AudioSelection>,
    pub start_time: DateTime<Utc>,
    #[ts(optional)]
    pub end_time: Option<DateTime<Utc>>,
    /// Framework turn holding this message, from `turn.id`; absent when the framework logs none.
    #[ts(optional)]
    pub turn_id: Option<String>,
    /// Turn that this message's turn answers, from `turn.reply_to` on the message or its turn span.
    #[ts(optional)]
    pub reply_to: Option<String>,
    /// Spans this message is observed to come from, like `generated_by` or `transcribed_by`.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    #[ts(optional, as = "Option<Vec<MessageJoin>>")]
    pub joins: Vec<MessageJoin>,
    /// Model calls whose input context included this message.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    #[ts(optional, as = "Option<Vec<ContextRef>>")]
    pub context_of: Vec<ContextRef>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "snake_case")]
pub enum VoiceSpeaker {
    User,
    Agent,
}

#[skip_serializing_none]
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, TS)]
pub struct MessageJoin {
    /// The logged relationship, like `generated_by` or `transcribed_by`.
    pub relationship: String,
    /// Span id of the joined span, as logged.
    pub span_id: String,
    /// Row id of the joined span; absent when that span is not in this trace.
    #[ts(optional)]
    pub step_id: Option<String>,
    /// Span the join passes through, like a synthesis span between agent speech and its model call.
    #[ts(optional)]
    pub via_span_id: Option<String>,
    /// Every source that observed this join.
    pub evidence: Vec<VoiceEvidence>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, TS)]
pub struct ContextRef {
    /// Row id of the model call.
    pub step_id: String,
    pub evidence: VoiceEvidence,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum VoiceEvidence {
    /// Logged by the source: a `metadata.links` entry or a native message/response id match.
    Observed { source: ObservedSource },
    /// Derived by Lingua; never from timing.
    Inferred { basis: InferenceBasis },
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "snake_case")]
pub enum ObservedSource {
    Link,
    MessageId,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "snake_case")]
pub enum InferenceBasis {
    /// The model input holds exactly one same-role message with exactly this text, with no link.
    TextMatch,
}

/// The voice messages one model call received as context.
#[skip_serializing_none]
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, TS)]
#[ts(export)]
pub struct VoiceContext {
    /// Row id of the model call.
    pub step_id: String,
    /// Ids of voice messages in its context, observed or inferred, ordered by speech start.
    pub message_ids: Vec<String>,
    /// User and assistant text inputs that match no voice message; absent until the input loads.
    #[ts(optional)]
    pub unmatched_input_count: Option<u32>,
    /// `input_context` links to spans that are not voice messages in this trace.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    #[ts(optional, as = "Option<Vec<String>>")]
    pub unresolved_span_ids: Vec<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize, TS)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum Scope {
    Span { id: String },
    Trace { trace_id: String },
    Thread { key: String, value: String },
}

